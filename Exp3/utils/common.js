// 栏目名称映射
const categoryNameMap = {};
categories.forEach(function (c) { categoryNameMap[c.id] = c.name; });

// 获取栏目列表（含"推荐"）
function getCategories() {
  return [{ id: 'all', name: '推荐' }].concat(categories);
}

// 时间筛选项
function getTimeFilters() {
  return [
    { id: 'all', name: '全部' },
    { id: '2026-08', name: '8月' },
    { id: '2026-07', name: '7月' },
    { id: 'earlier', name: '更早' }
  ];
}

// 判断新闻日期是否符合时间筛选
function matchTime(add_date, timeId) {
  if (!timeId || timeId === 'all') return true
  if (timeId === '2026-08') return add_date.indexOf('2026-08') === 0
  if (timeId === '2026-07') return add_date.indexOf('2026-07') === 0
  if (timeId === 'earlier') return add_date < '2026-07'
  return true
}

// 获取新闻列表（可按栏目 + 时间组合筛选，附带栏目名）
function getNewsList(categoryId, timeId) {
  let list = [];
  for (let i = 0; i < news.length; i++) {
    let categoryOk = !categoryId || categoryId === 'all' || news[i].category === categoryId
    if (categoryOk && matchTime(news[i].add_date, timeId)) {
      let obj = {};
      obj.id = news[i].id;
      obj.title = news[i].title;
      obj.poster = news[i].poster;
      obj.add_date = news[i].add_date;
      obj.category = news[i].category;
      obj.categoryName = categoryNameMap[news[i].category];
      list.push(obj);
    }
  }
  // 按日期倒序排列
  list.sort(function (a, b) { return a.add_date < b.add_date ? 1 : -1; });
  return list;
}

// 获取新闻内容
function getNewsDetail(newsID) {
  let msg = {
    code: '404',
    news: {}
  };
  for (let i = 0; i < news.length; i++) {
    if (newsID == news[i].id) {
      msg.code = '200';
      msg.news = news[i];
      msg.news.categoryName = categoryNameMap[news[i].category];
      break;
    }
  }
  return msg;
}

// 关键词搜索（标题 + 正文）
function searchNews(keyword) {
  keyword = (keyword || '').trim();
  if (!keyword) return [];
  let result = [];
  let list = getNewsList('all');
  for (let i = 0; i < list.length; i++) {
    let detail = getNewsDetail(list[i].id).news;
    if (detail.title.indexOf(keyword) > -1 || detail.content.indexOf(keyword) > -1) {
      result.push(list[i]);
    }
  }
  return result;
}

// 相关阅读：同栏目其他新闻（按日期倒序，最多 count 条）
function getRelatedNews(newsId, count) {
  count = count || 4;
  let detail = getNewsDetail(newsId).news;
  if (!detail || !detail.id) return [];
  let list = getNewsList(detail.category);
  let result = [];
  for (let i = 0; i < list.length && result.length < count; i++) {
    if (list[i].id != newsId) result.push(list[i]);
  }
  return result;
}

